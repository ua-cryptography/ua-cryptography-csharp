    {
        _ = number;
        byte[] k = H(key), v = H(iv), p = H(input), c = H(output);
        switch (mode)
        {
            case "ecb":
                var ecb = new Dstu7624Ecb(block, k);
                Assert.Equal(c, ecb.Encrypt(p));
                Assert.Equal(p, ecb.Decrypt(c));
                break;
            case "cbc":
                var cbc = new Dstu7624Cbc(block, k);
                Assert.Equal(c, cbc.Encrypt(v, p));
                Assert.Equal(p, cbc.Decrypt(v, c));
                break;
            case "cfb":
                var cfb = new Dstu7624Cfb(block, k, segment);
                Assert.Equal(c, cfb.Encrypt(v, p));
                Assert.Equal(p, cfb.Decrypt(v, c));
                break;
            case "ofb":
                var ofb = new Dstu7624Ofb(block, k, segment);
                Assert.Equal(c, ofb.Process(v, p));
                Assert.Equal(p, ofb.Process(v, c));
                break;
            case "ctr":
                var ctr = new Dstu7624Ctr(block, k);
                Assert.Equal(c, ctr.Process(v, p));
                Assert.Equal(p, ctr.Process(v, c));
                break;
            default:
                throw new NotSupportedException(mode);
        }
    }

