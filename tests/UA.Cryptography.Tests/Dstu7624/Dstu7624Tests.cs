    // -------------------------------------------------------------------------------------------
    // Reference vectors from BouncyCastle Java 1.86
    // -------------------------------------------------------------------------------------------

    public sealed record Vector(string Mode, int Block, string Key, string Iv, string Aad, string Input, string Output,
        int Segment, int MacBits, int Nb);

    private static readonly Lazy<List<Vector>> Vectors = new(() =>
    {
        using var stream = File.OpenRead(Path.Combine(TestFiles.Vectors, "dstu7624-bc-java-1.86.json"));
        var options = new JsonSerializerOptions { PropertyNameCaseInsensitive = true };
        return JsonSerializer.Deserialize<List<Vector>>(stream, options)!;
    });

    public static TheoryData<string> Modes()
    {
        var data = new TheoryData<string>();
        foreach (string mode in new[] { "ecb", "cbc", "cfb", "ofb", "ctr", "cmac", "kw", "ccm", "gcm", "gmac", "xts" })
            data.Add(mode);
        return data;
    }

    [Fact]
    public void AllReferenceVectorsAreLoaded()
    {
        Assert.Equal(590, Vectors.Value.Count);
        Assert.All(Vectors.Value, v => Assert.Contains(v.Block, new[] { 128, 256, 512 }));
        Assert.Equal(5, Vectors.Value.Select(v => (v.Block, v.Key.Length)).Distinct().Count()); // all block/key sizes
        Assert.Contains(Vectors.Value, v => v.Mode == "ccm" && v.Input.Length > 2 * 255 * 16); // the long CCM message
    }

    [Theory]
    [MemberData(nameof(Modes))]
    public void MatchesBouncyCastleJava(string mode)
    {
        List<Vector> vectors = Vectors.Value.Where(v => v.Mode == mode).ToList();
        Assert.NotEmpty(vectors);
        foreach (Vector v in vectors)
        {
            byte[] key = H(v.Key), iv = H(v.Iv), aad = H(v.Aad), input = H(v.Input), output = H(v.Output);
            string label = $"{mode}-{v.Block}/{key.Length * 8} in={input.Length} aad={aad.Length} iv={iv.Length} mac={v.MacBits} nb={v.Nb} seg={v.Segment}";
            switch (mode)
            {
                case "ecb":
                    var ecb = new Dstu7624Ecb(v.Block, key);
                    AssertEqual(output, ecb.Encrypt(input), label);
                    AssertEqual(input, ecb.Decrypt(output), label);
                    break;
                case "cbc":
                    var cbc = new Dstu7624Cbc(v.Block, key);
                    AssertEqual(output, cbc.Encrypt(iv, input), label);
                    AssertEqual(input, cbc.Decrypt(iv, output), label);
                    break;
                case "cfb":
                    var cfb = new Dstu7624Cfb(v.Block, key, v.Segment);
                    AssertEqual(output, cfb.Encrypt(iv, input), label);
                    AssertEqual(input, cfb.Decrypt(iv, output), label);
                    break;
                case "ofb":
                    AssertEqual(output, new Dstu7624Ofb(v.Block, key, v.Segment).Process(iv, input), label);
                    break;
                case "ctr":
                    AssertEqual(output, new Dstu7624Ctr(v.Block, key).Process(iv, input), label);
                    break;
                case "cmac":
                    AssertEqual(output, new Dstu7624Cmac(v.Block, key, v.MacBits).ComputeMac(input), label);
                    break;
                case "kw":
                    var kw = new Dstu7624KeyWrap(v.Block, key);
                    AssertEqual(output, kw.Wrap(input), label);
                    AssertEqual(input, kw.Unwrap(output), label);
                    break;
                case "ccm":
                    var ccm = new Dstu7624Ccm(v.Block, key, v.Nb);
                    AssertEqual(output, ccm.Encrypt(iv, aad, input, v.MacBits), label);
                    AssertEqual(input, ccm.Decrypt(iv, aad, output, v.MacBits), label);
                    AssertRejectsTampering(() => ccm.Decrypt(iv, aad, Flip(output), v.MacBits));
                    break;
                case "gcm":
                    var gcm = new Dstu7624Gcm(v.Block, key);
                    AssertEqual(output, gcm.Encrypt(iv, aad, input, v.MacBits), label);
                    AssertEqual(input, gcm.Decrypt(iv, aad, output, v.MacBits), label);
                    AssertRejectsTampering(() => gcm.Decrypt(iv, aad, Flip(output), v.MacBits));
                    break;
                case "gmac":
                    AssertEqual(output, new Dstu7624Gmac(v.Block, key).ComputeMac(iv, input, v.MacBits), label);
                    break;
                case "xts":
                    var xts = new Dstu7624Xts(v.Block, key);
                    AssertEqual(output, xts.Encrypt(iv, input), label);
                    AssertEqual(input, xts.Decrypt(iv, output), label);
                    break;
            }
        }
    }

    private static void AssertEqual(byte[] expected, byte[] actual, string label)
    {
        if (!expected.AsSpan().SequenceEqual(actual))
            Assert.Fail($"{label}: expected {Convert.ToHexString(expected)}, got {Convert.ToHexString(actual)}");
    }

    private static byte[] Flip(byte[] data)
    {
        byte[] copy = (byte[])data.Clone();
        copy[^1] ^= 1; // the last byte of the tag
        return copy;
    }

    private static void AssertRejectsTampering(Action decrypt) => Assert.Throws<CryptographicException>(decrypt);

    [Fact]
    public void InvalidParametersAreRejected()
    {
        Assert.Throws<ArgumentOutOfRangeException>(() => new Dstu7624Engine(192));
        Assert.Throws<ArgumentException>(() => new Dstu7624Ecb(256, new byte[16]));    // key shorter than the block
        Assert.Throws<ArgumentException>(() => new Dstu7624Ecb(128, new byte[64]));    // key longer than twice the block
        Assert.Throws<ArgumentException>(() => new Dstu7624Ecb(128, new byte[16]).Encrypt(new byte[15]));
        Assert.Throws<ArgumentException>(() => new Dstu7624Cmac(128, new byte[16], 128).ComputeMac(new byte[20]));
        Assert.Throws<ArgumentOutOfRangeException>(() => new Dstu7624Ccm(128, new byte[16]).Encrypt(new byte[16], default, new byte[1], 256));
        Assert.Throws<ArgumentOutOfRangeException>(() => new Dstu7624Gcm(128, new byte[16]).Encrypt(new byte[16], default, new byte[1], 32));
        Assert.Throws<ArgumentException>(() => new Dstu7624Xts(128, new byte[16]).Encrypt(new byte[8], new byte[16]));
    }
